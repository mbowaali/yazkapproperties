import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

interface ReceiptItem {
  description: string;
  quantity?: number;
  amount: number;
}

interface ReceiptData {
  receipt_no: string;
  tenant_name: string;
  unit_label?: string;
  amount: number;
  payment_date?: string;
  payment_method?: string;
  description?: string;
  currency?: string;
  paid_at?: string;
}

// Reusable receipt generation function that works for both admin invoices and tenant receipts
export async function generateAndDownloadReceipt(data: ReceiptData, items?: ReceiptItem[]) {
  try {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    
    // Add header with company branding
    doc.setFillColor(30, 64, 175); // Deep blue primary color
    doc.rect(0, 0, pageWidth, 45, "F");
    
    // Company name
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(24);
    doc.setFont("helvetica", "bold");
    doc.text("Yazkap Properties", pageWidth / 2, 25, { align: "center" });
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    doc.text("Premium Property Management Solutions", pageWidth / 2, 33, { align: "center" });
    
    // Receipt title badge
    doc.setFillColor(22, 163, 74); // Green for success
    (doc as any).roundedRect(pageWidth - 60, 15, 50, 18, 3, "F");
    doc.setFontSize(11);
    doc.setFont("helvetica", "bold");
    doc.text("PAID", pageWidth - 35, 27, { align: "center" });

    // Receipt metadata section
    doc.setTextColor(51, 51, 51);
    doc.setFontSize(10);
    doc.setFont("helvetica", "bold");
    doc.text("RECEIPT", 14, 60);
    doc.setFont("helvetica", "normal");
    
    // Receipt number and dates
    doc.text(`Receipt #: ${data.receipt_no}`, 14, 68);
    doc.text(`Issue Date: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, 14, 75);
    if (data.payment_date || data.paid_at) {
      const paymentDate = data.paid_at || data.payment_date;
      doc.text(`Payment Date: ${new Date(paymentDate!).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, 14, 82);
    }

    // Billed to section with background
    doc.setFillColor(248, 250, 252);
    (doc as any).roundedRect(14, 90, pageWidth - 28, 45, 4, "F");
    
    doc.setFont("helvetica", "bold");
    doc.text("Bill To:", 20, 102);
    doc.setFont("helvetica", "normal");
    doc.text(data.tenant_name, 20, 110);
    doc.text(`Unit: ${data.unit_label || "Property Unit"}`, 20, 118);

    // Payment items table
    const tableItems = items || [{
      description: data.description || "Rent Payment",
      quantity: 1,
      amount: data.amount
    }];

    autoTable(doc, {
      startY: 145,
      head: [["Description", "Quantity", "Unit Price", "Total"]],
      body: tableItems.map((item) => [
        item.description,
        item.quantity || 1,
        `AED ${(item.amount / (item.quantity || 1)).toFixed(2)}`,
        `AED ${item.amount.toFixed(2)}`
      ]),
      theme: "grid",
      headStyles: { 
        fillColor: [30, 64, 175],
        textColor: 255,
        fontStyle: 'bold'
      },
      alternateRowStyles: { fillColor: [248, 250, 252] },
      foot: [
        [
          { content: "", colSpan: 3 },
          { content: "Total", styles: { fontStyle: 'bold' } }
        ],
        [
          { content: "", colSpan: 3 },
          { content: `AED ${data.amount.toFixed(2)}`, styles: { fontStyle: 'bold' } }
        ],
        [
          { content: "", colSpan: 3 },
          { content: "Amount Paid", styles: { fontStyle: 'bold', fillColor: [220, 252, 231] } }
        ],
        [
          { content: "", colSpan: 3 },
          { content: `AED ${data.amount.toFixed(2)}`, styles: { fontStyle: 'bold', fillColor: [220, 252, 231] } }
        ]
      ],
    });

    // Add footer with contact info
    const finalY = (doc as any).lastAutoTable.finalY || 200;
    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.text("Thank you for your payment. This receipt was generated by Yazkap Properties Portal.", pageWidth / 2, finalY + 20, { align: "center" });
    doc.text("+971 50 512 276 | info@yazkapproperties.com", pageWidth / 2, finalY + 28, { align: "center" });

    // Save the PDF
    doc.save(`Yazkap-Receipt-${data.receipt_no}.pdf`);
    
    return { success: true };
  } catch (error) {
    console.error("Error generating receipt:", error);
    alert("Failed to generate receipt. Please check the console for details.");
    return { success: false, error };
  }
}